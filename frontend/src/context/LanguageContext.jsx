// Pre-sorted multi-word phrases for fast parsing
const SORTED_PHRASES = Object.keys(PHRASES_MAP).sort((a, b) => b.length - a.length);

/**
 * Universal Multi-Stage Translation Pipeline across all 18 Indian Languages
 */
function translateFullText(text, lang) {
  if (!text || !text.trim() || lang === "en") return text;

  let result = text;

  // Stage 1: Match and replace multi-word phrases (case-insensitive)
  for (const phrase of SORTED_PHRASES) {
    const regex = new RegExp(phrase.replace(/[.*+?^${}()|[\]\\]/g, "\\$&"), "gi");
    if (regex.test(result)) {
      const trans = (PHRASES_MAP[phrase] && PHRASES_MAP[phrase][lang]) || phrase;
      result = result.replace(regex, trans);
    }
  }

  // Stage 2: Match and replace single word tokens using word boundary (\bword\b)
  for (const word of Object.keys(WORDS_MAP)) {
    const regex = new RegExp(`\\b${word}\\b`, "gi");
    if (regex.test(result)) {
      const trans = (WORDS_MAP[word] && WORDS_MAP[word][lang]) || word;
      result = result.replace(regex, trans);
    }
  }

  return result;
}

const LanguageContext = createContext();

export function LanguageProvider({ children }) {
  const [currentLang, setCurrentLang] = useState(() => {
    return localStorage.getItem("fintwin_language") || "en";
  });

  const changeLanguage = (langCode) => {
    if (SUPPORTED_LANGUAGES.some((l) => l.id === langCode)) {
      setCurrentLang(langCode);
      localStorage.setItem("fintwin_language", langCode);
    }
  };

  const t = (keyOrPhrase, fallback = "") => {
    if (!keyOrPhrase) return "";
    return translateFullText(String(keyOrPhrase), currentLang) || fallback || keyOrPhrase;
  };

  const activeLanguageMeta =
    SUPPORTED_LANGUAGES.find((l) => l.id === currentLang) || SUPPORTED_LANGUAGES[0];

  // =========================================================================
  // NATIVE DOM AUTO-TRANSLATION PIPELINE (All 18 Languages Active)
  // =========================================================================
  useEffect(() => {
    if (typeof document === "undefined") return;

    if (currentLang === "en") {
      // Instant Lossless Restore to Original English
      const walker = document.createTreeWalker(
        document.body,
        NodeFilter.SHOW_TEXT,
        null
      );
      let node;
      while ((node = walker.nextNode())) {
        if (node.__ftOriginalText !== undefined) {
          if (node.nodeValue !== node.__ftOriginalText) {
            node.nodeValue = node.__ftOriginalText;
          }
        }
      }
      return;
    }

    const translateNode = (node) => {
      const parentTag = node.parentElement?.tagName?.toLowerCase();
      if (
        parentTag === "script" ||
        parentTag === "style" ||
        parentTag === "noscript" ||
        parentTag === "code"
      ) {
        return;
      }
      if (node.__ftOriginalText === undefined) {
        node.__ftOriginalText = node.nodeValue;
      }
      const orig = node.__ftOriginalText;
      if (!orig || !orig.trim()) return;

      const translated = translateFullText(orig, currentLang);
      if (node.nodeValue !== translated) {
        node.nodeValue = translated;
      }
    };

    const translateTree = () => {
      const walker = document.createTreeWalker(
        document.body,
        NodeFilter.SHOW_TEXT,
        null
      );
      let node;
      while ((node = walker.nextNode())) {
        translateNode(node);
      }
    };

    // Initial pass
    translateTree();

    // Continuous observation for route transitions and dynamic modals
    let timeoutId = null;
    const observer = new MutationObserver((mutations) => {
      let shouldTranslate = false;
      for (const m of mutations) {
        if (m.type === "childList" && m.addedNodes.length > 0) {
          shouldTranslate = true;
          break;
        }
        if (m.type === "characterData") {
          if (
            m.target.__ftOriginalText === undefined ||
            m.target.nodeValue === m.target.__ftOriginalText
          ) {
            shouldTranslate = true;
            break;
          }
        }
      }
      if (shouldTranslate) {
        if (timeoutId) clearTimeout(timeoutId);
        timeoutId = setTimeout(() => {
          translateTree();
        }, 20);
      }
    });

    observer.observe(document.body, {
      childList: true,
      subtree: true,
      characterData: true,
    });

    return () => {
      observer.disconnect();
      if (timeoutId) clearTimeout(timeoutId);
    };
  }, [currentLang]);

  return (
    <LanguageContext.Provider
      value={{
        currentLang,
        changeLanguage,
        t,
        supportedLanguages: SUPPORTED_LANGUAGES,
        activeLanguageMeta,
      }}
    >
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error("useLanguage must be used within a LanguageProvider");
  }
  return context;
}
